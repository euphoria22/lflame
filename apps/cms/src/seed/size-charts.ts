export async function seedSizeCharts(payload: Payload): Promise<void> {
  const found = await payload.find({ collection: "size-charts", limit: 1, depth: 0 })
  if (found.totalDocs > 0) return
  for (const c of CHARTS) {
    await payload.create({ collection: "size-charts", data: c as never })
  }
  payload.logger.info(`Созданы таблицы размеров: ${CHARTS.length}`)
}
