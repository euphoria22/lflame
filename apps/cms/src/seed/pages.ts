export async function seedPages(payload: Payload): Promise<void> {
  for (const p of PAGES) {
    const exists = await payload.count({ collection: "pages", where: { slug: { equals: p.slug } } })
    if (exists.totalDocs) continue
    await payload.create({
      collection: "pages",
      data: { slug: p.slug, title: p.title, order: p.order, intro: p.intro, content: md(p.text) as never },
    })
    payload.logger.info(`Создана страница «${p.title}» (/${p.slug})`)
  }
}
